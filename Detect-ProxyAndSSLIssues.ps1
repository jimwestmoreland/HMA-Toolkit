#region Auto-Detect Exchange Servers
function Get-ExchangeServersToScan {
    param(
        [string[]]$SpecificServers,
        [string]$Role
    )
    
    $servers = @()
    
    if ($SpecificServers -and $SpecificServers.Count -gt 0) {
        Write-Host "Using specified server(s): $($SpecificServers -join ', ')" -ForegroundColor Cyan
        return $SpecificServers
    }
    
    Write-Host "Auto-detecting Exchange servers..." -ForegroundColor Yellow
    
    try {
        $exServers = Get-ExchangeServer -ErrorAction SilentlyContinue
        
        if ($exServers) {
            foreach ($srv in $exServers) {
                # Skip Edge Transport servers
                if ($srv.ServerRole -match "Edge") {
                    Write-Host "  Skipping $($srv.Name) (Edge Transport role)" -ForegroundColor Gray
                    continue
                }
                
                $include = $false
                switch ($Role) {
                    "ClientAccess" {
                        if ($srv.ServerRole -match 'ClientAccess|Mailbox') { $include = $true }
                    }
                    "Mailbox" {
                        if ($srv.ServerRole -match "Mailbox") { $include = $true }
                    }
                    "All" {
                        if ($srv.ServerRole -match 'ClientAccess|Mailbox') { $include = $true }
                    }
                }
                
                if ($include) {
                    $servers += $srv.Name
                }
            }
            
            Write-Host "  Found $($servers.Count) Exchange server(s)" -ForegroundColor Green
            return $servers
        }
    } catch {
        Write-Host "  Get-ExchangeServer not available (not in EMS?)" -ForegroundColor Gray
    }
    
    try {
        $configNC = ([ADSI]"LDAP://RootDSE").configurationNamingContext
        $exchServersPath = "LDAP://CN=Servers,CN=Exchange Administrative Group (FYDIBOHF23SPDLT),CN=Administrative Groups,CN=First Organization,CN=Microsoft Exchange,CN=Services,$configNC"
        
        $searcher = New-Object DirectoryServices.DirectorySearcher
        $searcher.SearchRoot = [ADSI]$exchServersPath
        $searcher.Filter = "(objectClass=msExchExchangeServer)"
        $searcher.PageSize = 100
        
        $results = $searcher.FindAll()
        
        foreach ($result in $results) {
            $serverName = $result.Properties["cn"][0]
            $servers += $serverName
        }
        
        if ($servers.Count -gt 0) {
            Write-Host "  Found $($servers.Count) Exchange server(s) via AD query" -ForegroundColor Green
            return $servers
        }
    } catch {
        Write-Host "  AD query for Exchange servers failed" -ForegroundColor Gray
    }
    
    Write-Host "  Could not auto-detect servers. Using local server: $env:COMPUTERNAME" -ForegroundColor Yellow
    return @($env:COMPUTERNAME)
}

function Test-ServerConnectivity {
    param([string]$ServerName)
    
    $pingResult = Test-Connection -ComputerName $ServerName -Count 1 -Quiet -ErrorAction SilentlyContinue
    if (-not $pingResult) {
        return @{ Success = $false; Error = 'Server not reachable (ping failed)'; HasExchange = $false }
    }
    
    $uncPath = '\\' + $ServerName + '\C$'
    if (-not (Test-Path $uncPath -ErrorAction SilentlyContinue)) {
        $shareErr = 'Cannot access admin share (' + $uncPath + ')'
        return @{ Success = $false; Error = $shareErr; HasExchange = $false }
    }
    
    $exchangePath = '\\' + $ServerName + '\C$\Program Files\Microsoft\Exchange Server\V15'
    if (-not (Test-Path $exchangePath -ErrorAction SilentlyContinue)) {
        return @{ Success = $false; Error = 'Exchange Server not installed'; HasExchange = $false }
    }
    
    $httpProxyPath = '\\' + $ServerName + '\C$\Program Files\Microsoft\Exchange Server\V15\Logging\HttpProxy'
    $hasHttpProxyLogs = Test-Path $httpProxyPath -ErrorAction SilentlyContinue
    
    if (-not $hasHttpProxyLogs) {
        return @{ Success = $false; Error = "No HttpProxy logs found"; HasExchange = $true }
    }
    
    return @{ Success = $true; Error = $null; HasExchange = $true }
}
