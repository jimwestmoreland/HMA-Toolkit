    )
    
    Write-Host "`n[SERVER: $TargetServer]" -ForegroundColor Magenta
    Write-Host "----------------------------------------" -ForegroundColor Magenta
    
    # Test connectivity
    $connectivity = Test-ServerConnectivity -ServerName $TargetServer
    if (-not $connectivity.Success) {
        Write-Host "  SKIPPED: $($connectivity.Error)" -ForegroundColor Red
        Add-Indicator -Server $TargetServer -Source "Connectivity" -Severity "ERROR" `
            -Pattern "Server Unreachable" -Details $connectivity.Error
        return
    }
    
    Write-Host "  Connectivity OK" -ForegroundColor Green

    #region HttpProxy Logs
    Write-Host "  Checking HttpProxy Logs..." -ForegroundColor Yellow

    $HttpProxyLogPath = '\\' + $TargetServer + '\C$\Program Files\Microsoft\Exchange Server\V15\Logging\HttpProxy'
    $protocols = @("Eas", "Autodiscover", "Mapi", "Ews")

    foreach ($protocol in $protocols) {
        $logPath = Join-Path $HttpProxyLogPath $protocol
        
        if (Test-Path $logPath) {
            Write-Host "    Scanning $protocol logs..." -ForegroundColor Gray
            
            try {
                $logFiles = Get-ChildItem -Path $logPath -Filter "*.log" -ErrorAction SilentlyContinue | 
                    Where-Object { $_.LastWriteTime -ge $ScanStartTime }
                
                foreach ($logFile in $logFiles) {
                    $content = Get-Content $logFile.FullName -ErrorAction SilentlyContinue
                    
                    foreach ($line in $content) {
                        if ($line -match "^#" -or $line -match "^DateTime") { continue }
                        if ($FilterUserEmail -and $line -notmatch [regex]::Escape($FilterUserEmail)) { continue }
                        
                        # Pattern 1: Empty Authorization header
                        if ($line -match 'AuthorizationHeader=;' -or $line -match 'AuthorizationHeader=\s*$') {
                            $srcStr = 'HttpProxy/' + $protocol
                            Add-Indicator -Server $TargetServer -Source $srcStr -Severity "HIGH" `
                                -Pattern "Empty Authorization Header" `
                                -Details "Bearer token may have been stripped by proxy" `
                                -Timestamp ($line -split ",")[0]
                        }
                        
                        # Pattern 2: Connection reset/abort
                        if ($line -match 'ConnectionReset|Abort|TimedOut|ConnectionClosed') {
                            Add-Indicator -Server $TargetServer -Source "HttpProxy/$protocol" -Severity "MEDIUM" `
                                -Pattern "Connection Terminated" `
                                -Details "Proxy may be terminating connections unexpectedly" `
                                -Timestamp ($line -split ",")[0]
                        }
                        
                        # Pattern 3: X-Forwarded-For with multiple IPs
                        if ($line -match "X-Forwarded-For" -and $line -match "\d+\.\d+\.\d+\.\d+.*,.*\d+\.\d+\.\d+\.\d+") {
                            Add-Indicator -Server $TargetServer -Source "HttpProxy/$protocol" -Severity "INFO" `
                                -Pattern "Multiple X-Forwarded-For IPs" `
                                -Details "Traffic is passing through proxy" `
                                -Timestamp ($line -split ",")[0]
                        }
                        
                        # Pattern 4: SSL/TLS errors
                        if ($line -match 'Ssl|Tls|Certificate|SecureChannel') {
                            if ($line -match 'Error|Failed|Invalid|Untrusted') {
                                Add-Indicator -Server $TargetServer -Source "HttpProxy/$protocol" -Severity "HIGH" `
                                    -Pattern "SSL/TLS Error" `
                                    -Details "Possible SSL inspection interference" `
                                    -Timestamp ($line -split ",")[0]
                            }
                        }
                        
                        # Pattern 5: 401 on Autodiscover
                        if ($line -match "401" -and $line -match 'Autodiscover|autodiscover\.xml') {
                            Add-Indicator -Server $TargetServer -Source "HttpProxy/$protocol" -Severity "MEDIUM" `
                                -Pattern "401 on Autodiscover" `
                                -Details "Client may be falling back to legacy auth" `
                                -Timestamp ($line -split ",")[0]
                        }
                        
                        # Pattern 6: Zero-byte response
                        if ($line -match "ResponseSize=0" -and $line -notmatch '204|304') {
                            Add-Indicator -Server $TargetServer -Source "HttpProxy/$protocol" -Severity "MEDIUM" `
                                -Pattern "Zero-byte Response" `
                                -Details "Proxy may be blocking response body" `
                                -Timestamp ($line -split ",")[0]
                        }
                        
                        # Pattern 7: High latency
                        if ($line -match 'TotalRequestTime=(\d+)') {
                            $latency = [int]$Matches[1]
                            if ($latency -gt 30000) {
                                $srcStr = 'HttpProxy/' + $protocol
                                $latencyPattern = 'High Latency (' + $latency + ' ms)'
                                Add-Indicator -Server $TargetServer -Source $srcStr -Severity "MEDIUM" `
                                    -Pattern $latencyPattern `
                                    -Details "Proxy may be adding significant delay" `
                                    -Timestamp ($line -split ",")[0]
                            }
                        }
                    }
                }
            } catch {
                Write-Host "      Error reading $protocol logs: $_" -ForegroundColor Red
            }
        }
    }
    #endregion

    #region IIS Logs
    Write-Host "  Checking IIS Logs..." -ForegroundColor Yellow

    $iisPath1 = '\\' + $TargetServer + '\C$\inetpub\logs\LogFiles\W3SVC1'
    $iisPath2 = '\\' + $TargetServer + '\C$\inetpub\logs\LogFiles\W3SVC2'
    $IISLogPaths = @($iisPath1, $iisPath2)

    foreach ($iisPath in $IISLogPaths) {
        if (Test-Path $iisPath) {
            Write-Host "    Scanning $iisPath..." -ForegroundColor Gray
            
            try {
                $logFiles = Get-ChildItem -Path $iisPath -Filter "*.log" -ErrorAction SilentlyContinue | 
                    Where-Object { $_.LastWriteTime -ge $ScanStartTime } |
                    Select-Object -Last 5
                
                foreach ($logFile in $logFiles) {
                    $content = Get-Content $logFile.FullName -Tail 5000 -ErrorAction SilentlyContinue
                    
                    $pattern401Count = 0
                    $pattern200Count = 0
                    
                    foreach ($line in $content) {
                        if ($line -match "^#") { continue }
                        if ($FilterUserEmail -and $line -notmatch [regex]::Escape($FilterUserEmail)) { continue }
                        
                        if ($line -match '(Microsoft-Server-ActiveSync|Autodiscover)' -and $line -match "\s401\s") {
                            $pattern401Count++
                        }
                        
                        if ($line -match '(Microsoft-Server-ActiveSync|Autodiscover)' -and $line -match "\s200\s") {
                            $pattern200Count++
                        }
                        
                        if ($line -match '\s(500|502|503|504)\s') {
                            Add-Indicator -Server $TargetServer -Source "IIS" -Severity "MEDIUM" `
                                -Pattern "Server Error (5xx)" `
                                -Details $line.Substring(0, [Math]::Min(200, $line.Length)) `
                                -Timestamp (($line -split " ")[0..1] -join " ")
                        }
                    }
                    
                    $minFailureThreshold = if ($FilterUserEmail) { 1 } else { 2 }
                    if ($pattern401Count -ge $minFailureThreshold -and $pattern401Count -gt $pattern200Count) {
                        Add-Indicator -Server $TargetServer -Source "IIS" -Severity "HIGH" `
                            -Pattern "High 401 Error Rate" `
                            -Details "Found $pattern401Count failures vs $pattern200Count successes" `
                            -Timestamp $logFile.Name
                    }
                }
            } catch {
                Write-Host "      Error reading IIS logs: $_" -ForegroundColor Red
            }
        }
    }
    #endregion

    #region Windows Event Logs
    Write-Host "  Checking Windows Event Logs..." -ForegroundColor Yellow

    try {
        $sslEvents = Get-WinEvent -ComputerName $TargetServer -FilterHashtable @{
            LogName = 'System'
            ProviderName = 'Schannel'
            StartTime = $ScanStartTime
            Level = 2,3
        } -MaxEvents 50 -ErrorAction SilentlyContinue

        foreach ($evt in $sslEvents) {
            Add-Indicator -Server $TargetServer -Source "Schannel" -Severity "MEDIUM" `
                -Pattern "SSL/TLS Error (Event $($evt.Id))" `
                -Details $evt.Message.Substring(0, [Math]::Min(200, $evt.Message.Length)) `
                -Timestamp $evt.TimeCreated.ToString()
        }
    } catch {
        Write-Host "    Could not read Schannel events" -ForegroundColor Gray
    }

    # OAuth Events
    Write-Host "  Checking MSExchange OAuth Events..." -ForegroundColor Yellow
    $oauthEvents = Get-OAuthEventLogErrors -Server $TargetServer -Since $ScanStartTime
    $script:OAuthEvents += $oauthEvents
    
    foreach ($evt in $oauthEvents | Where-Object { $_.Level -match 'Error|Warning' }) {
        $severity = if ($evt.IsCertRelated -or $evt.IsTokenValidationError) { "HIGH" } else { "MEDIUM" }
        Add-Indicator -Server $TargetServer -Source "OAuth Events" -Severity $severity `
            -Pattern "OAuth Error (Event $($evt.EventId))" `
            -Details $evt.Message.Substring(0, [Math]::Min(300, $evt.Message.Length)) `
            -Timestamp $evt.TimeCreated.ToString()
    }
    
    # CAPI2 Events
    Write-Host "  Checking CAPI2 Certificate Events..." -ForegroundColor Yellow
    $capi2Events = Get-CAPI2CertificateErrors -Server $TargetServer -Since $ScanStartTime
    $script:CAPI2Events += $capi2Events
    
    foreach ($evt in $capi2Events | Where-Object { $_.HasNonMicrosoftIssuer -or $_.IsAzureADRelated }) {
        Add-Indicator -Server $TargetServer -Source "CAPI2" -Severity "HIGH" `
            -Pattern "Certificate Validation Issue" `
            -Details "Azure AD cert event with potential proxy CA detected" `
            -Timestamp $evt.TimeCreated.ToString()
    }
    
    # Auth Patterns
    Write-Host "  Analyzing Authentication Patterns..." -ForegroundColor Yellow
    $authStats = Get-AuthenticationPatterns -Server $TargetServer -Since $ScanStartTime
    $script:AuthPatterns[$TargetServer] = $authStats
    
    $oauthTotal = $authStats.OAuthSuccess + $authStats.OAuthFailure
    if ($oauthTotal -gt 0) {
        $failRate = [math]::Round(($authStats.OAuthFailure / $oauthTotal) * 100, 1)
        $failMsg = '    OAuth: ' + $authStats.OAuthSuccess + ' success, ' + $authStats.OAuthFailure + ' fail (' + $failRate + '%)'
        Write-Host $failMsg -ForegroundColor $(if ($failRate -gt 10) { 'Red' } elseif ($failRate -gt 5) { 'Yellow' } else { 'Green' })
        Write-Host "    NTLM Fallback: $($authStats.NTLMFallback)" -ForegroundColor $(if ($authStats.NTLMFallback -gt 0) { "Yellow" } else { "Gray" })
    }
    #endregion

    #region SSL Certificate Chain Check
    if ($DoSSLCheck) {
        Write-Host "  Checking SSL Certificate Chains to Azure AD..." -ForegroundColor Yellow
        $certResults = Test-CertificateChain -Server $TargetServer
        $script:CertChainResults += $certResults
        
        foreach ($check in $certResults) {
            if ($check.Error) {
                Write-Host "    $($check.Endpoint): ERROR - $($check.Error)" -ForegroundColor Yellow
                Add-Indicator -Server $TargetServer -Source "SSL Check" -Severity "MEDIUM" `
                    -Pattern "Azure AD Connection Error" `
                    -Details "$($check.Endpoint): $($check.Error)"
            } elseif ($check.IsProxyIntercepted) {
                Write-Host "    $($check.Endpoint): INTERCEPTED by $($check.RootIssuer)" -ForegroundColor Red
                Add-Indicator -Server $TargetServer -Source "SSL Check" -Severity "CRITICAL" `
                    -Pattern "SSL Interception Detected" `
                    -Details "$($check.Endpoint) certificate issued by non-Microsoft CA: $($check.Issuer)"
            } else {
                Write-Host "    $($check.Endpoint): OK (Microsoft CA)" -ForegroundColor Green
            }
        }
    }
    #endregion
    
    Write-Host "  [DONE] Server scan complete" -ForegroundColor Green
}
