#region Azure AD Sign-in Logs
function Get-AzureADSignInFailures {
    param([datetime]$Since, [string]$FilterUserEmail)
    
    Write-Host "`nChecking Azure AD Sign-in Logs..." -ForegroundColor Yellow
    
    $graphConnected = $false
    try {
        $context = Get-MgContext -ErrorAction SilentlyContinue
        if ($context) { $graphConnected = $true }
    } catch { }
    
    if (-not $graphConnected) {
        Write-Host "  Not connected to Microsoft Graph. Run: Connect-MgGraph -Scopes 'AuditLog.Read.All'" -ForegroundColor Gray
        return
    }
    
    try {
        $filter = "createdDateTime ge $($Since.ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ'))"
        $filter += " and (status/errorCode ne 0)"
        $filter += " and (appDisplayName eq 'Microsoft Outlook' or appDisplayName eq 'Outlook Mobile')"
        
        if ($FilterUserEmail) {
            $filter += " and userPrincipalName eq '$FilterUserEmail'"
        }
        
        $signIns = Get-MgAuditLogSignIn -Filter $filter -Top 100 -ErrorAction SilentlyContinue
        
        foreach ($signIn in $signIns) {
            if ($signIn.Status.ErrorCode -in @(50053, 50126, 50076, 50079, 500121, 50074)) {
                Add-Indicator -Server "Azure AD (Cloud)" -Source "Azure AD" -Severity "HIGH" `
                    -Pattern "Sign-in Failed (Error $($signIn.Status.ErrorCode))" `
                    -Details "User: $($signIn.UserPrincipalName) - $($signIn.Status.FailureReason) - IP: $($signIn.IpAddress)" `
                    -Timestamp $signIn.CreatedDateTime.ToString()
            }
        }
        
        Write-Host "  Analyzed $($signIns.Count) failed sign-ins" -ForegroundColor Gray
    } catch {
        Write-Host "  Error querying Azure AD: $_" -ForegroundColor Red
    }
}
