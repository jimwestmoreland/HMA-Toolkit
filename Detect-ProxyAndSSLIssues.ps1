#region Log Analysis Functions
function Get-OAuthEventLogErrors {
    param(
        [string]$Server,
        [datetime]$Since
    )
    
    $results = @()
    
    try {
        $events = Get-WinEvent -ComputerName $Server -FilterHashtable @{
            LogName = 'Application'
            ProviderName = 'MSExchange OAuth'
            StartTime = $Since
        } -MaxEvents 500 -ErrorAction SilentlyContinue
        
        foreach ($evt in $events) {
            $msg = $evt.Message.ToLower()
            
            $eventData = [PSCustomObject]@{
                Server = $Server
                TimeCreated = $evt.TimeCreated
                EventId = $evt.Id
                Level = $evt.LevelDisplayName
                Message = $evt.Message
                IsCertRelated = $msg -match 'certificate|ssl|tls|chain|trust|x509|signature verification|signing key|untrusted'
                IsMetadataRelated = $msg -match 'metadata|could not retrieve|connection was closed|webexception|timeout'
                IsTokenValidationError = $msg -match 'token.*invalid|invalid.*token|validation failed|signature.*failed|jwt|bearer'
            }
            
            $results += $eventData
        }
    } catch {
        $errMsg = '    Could not read OAuth events from ' + $Server
        Write-Host $errMsg -ForegroundColor Gray
    }
    
    return $results
}

function Get-CAPI2CertificateErrors {
    param(
        [string]$Server,
        [datetime]$Since
    )
    
    $results = @()
    
    try {
        $events = Get-WinEvent -ComputerName $Server -FilterHashtable @{
            LogName = 'Microsoft-Windows-CAPI2/Operational'
            StartTime = $Since
        } -MaxEvents 1000 -ErrorAction SilentlyContinue
        
        foreach ($evt in $events) {
            $isAzureAD = $false
            foreach ($endpoint in $script:AzureADEndpoints) {
                if ($evt.Message -match [regex]::Escape($endpoint)) {
                    $isAzureAD = $true
                    break
                }
            }
            
            $hasNonMicrosoftIssuer = $evt.Message -match 'issuer' -and $evt.Message -notmatch 'Microsoft|DigiCert|Baltimore'
            $isFailure = $evt.Message -match 'Error|fail|untrusted|revoked|expired|invalid' -or 
                         $evt.LevelDisplayName -match 'Error|Warning'
            
            if ($isAzureAD -or ($isFailure -and $hasNonMicrosoftIssuer)) {
                $results += [PSCustomObject]@{
                    Server = $Server
                    TimeCreated = $evt.TimeCreated
                    EventId = $evt.Id
                    Level = $evt.LevelDisplayName
                    Message = $evt.Message
                    IsAzureADRelated = $isAzureAD
                    HasNonMicrosoftIssuer = $hasNonMicrosoftIssuer
                }
            }
        }
    } catch {
        $errMsg = '    CAPI2 logs not available on ' + $Server + ' (may need to be enabled)'
        Write-Host $errMsg -ForegroundColor Gray
    }
    
    return $results
}

function Get-AuthenticationPatterns {
    param(
        [string]$Server,
        [datetime]$Since
    )
    
    $results = @{
        OAuthSuccess = 0
        OAuthFailure = 0
        NTLMFallback = 0
        BasicFallback = 0
        AnonymousDenied = 0
    }
    
    $logPath = '\\' + $Server + '\C$\Program Files\Microsoft\Exchange Server\V15\Logging\HttpProxy\Eas'
    
    if (-not (Test-Path $logPath -ErrorAction SilentlyContinue)) {
        return $results
    }
    
    try {
        $logFiles = Get-ChildItem -Path $logPath -Filter "*.log" -ErrorAction SilentlyContinue | 
            Where-Object { $_.LastWriteTime -ge $Since } |
            Sort-Object LastWriteTime -Descending |
            Select-Object -First 10
        
        foreach ($logFile in $logFiles) {
            $content = Get-Content $logFile.FullName -ErrorAction SilentlyContinue | Select-Object -Last 5000
            
            foreach ($line in $content) {
                if ($line -match "^#" -or [string]::IsNullOrWhiteSpace($line)) { continue }
                
                $fields = $line -split ","
                if ($fields.Count -lt 20) { continue }
                
                $authType = $fields[11]
                $httpStatus = $fields[19]
                
                switch -Regex ($authType) {
                    "OAuth|Bearer" {
                        if ($httpStatus -eq "200") { $results.OAuthSuccess++ }
                        else { $results.OAuthFailure++ }
                    }
                    "NTLM|Negotiate" { $results.NTLMFallback++ }
                    "Basic" { $results.BasicFallback++ }
                    "Anonymous|^$" { 
                        if ($httpStatus -eq "401") { $results.AnonymousDenied++ }
                    }
                }
            }
        }
    } catch {
        Write-Host "    Error reading EAS logs from $Server" -ForegroundColor Gray
    }
    
    return $results
}
