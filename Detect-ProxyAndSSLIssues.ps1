<#
# VERSION: 2026-02-04 UTC
.SYNOPSIS
    Comprehensive detection of proxy interference and SSL inspection issues affecting Exchange HMA.
    
.DESCRIPTION
    This script combines proxy interference detection with SSL inspection analysis to provide
    complete diagnostics for Hybrid Modern Authentication issues.
    
    OUTPUT FILES (2 files generated by default):
    1. ProxySSL-Analysis-[timestamp].txt - Summary report with findings and recommendations
    2. ProxySSL-Transcript-[timestamp].txt - Full verbose output with all event details
    
    The transcript file contains the complete console output including all individual
    events, log entries, and detailed findings that may be useful for root cause analysis.
    
    Detection capabilities:
    - Empty/stripped Authorization headers (Bearer token removed by proxy)
    - SSL/TLS inspection evidence (certificate chain analysis)
    - MSExchange OAuth events (token validation, cert errors, metadata failures)
    - CAPI2 certificate validation events
    - Connection resets, timeouts, and high error rates
    - IIS and HttpProxy log analysis
    - Known proxy header patterns
    - Authentication fallback patterns (NTLM/Basic instead of OAuth)
    - Azure AD sign-in log failures (optional)
    
.PARAMETER HoursBack
    How many hours of logs to analyze. Default is 24.

.PARAMETER ExchangeServers
    Specific Exchange server(s) to check. Accepts a single server name or array of names.
    If not specified, auto-detects all relevant Exchange servers.

.PARAMETER ServerRole
    Filter auto-detected servers by role. Valid values: ClientAccess, Mailbox, All (default: All)

.PARAMETER IncludeAzureAD
    If specified and connected to Microsoft Graph, queries sign-in logs for failures.

.PARAMETER UserEmail
    Filter logs to a specific user's email address.

.PARAMETER IncludeSSLCheck
    Perform live SSL certificate chain verification to Azure AD endpoints.
    This actively tests if SSL inspection is occurring. Default is true.

.PARAMETER OutputPath
    Path to save the report. If not specified, generates a timestamped file in current directory.

.PARAMETER NoFileOutput
    Skip writing report to file (console output only).

.EXAMPLE
    .\Detect-ProxyAndSSLIssues.ps1
    # Auto-detect all Exchange servers and analyze last 24 hours of logs

.EXAMPLE
    .\Detect-ProxyAndSSLIssues.ps1 -ExchangeServers "EX01","EX02" -HoursBack 48
    # Scan specific servers for 48 hours

.EXAMPLE
    .\Detect-ProxyAndSSLIssues.ps1 -UserEmail "user@contoso.com" -HoursBack 8
    # Check 8 hours for a specific user across all servers

.EXAMPLE
    Connect-MgGraph -Scopes "AuditLog.Read.All"
    .\Detect-ProxyAndSSLIssues.ps1 -IncludeAzureAD
    # Include Azure AD sign-in log analysis

.EXAMPLE
    .\Detect-ProxyAndSSLIssues.ps1 -IncludeSSLCheck:$false
    # Skip live SSL certificate checks (log analysis only)

.NOTES
    Author: HMA Troubleshooting Toolkit
    Date: 2026-02-04
    Run from Exchange Management Shell for best results.
    Requires appropriate permissions to access remote servers via UNC paths and WinRM.
#>

